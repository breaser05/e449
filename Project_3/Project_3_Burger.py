def convolutions(h_hat, r_hat):
    h = (2*N)*np.fft.irfft(h_hat,n=2*N)
    r = (2*N)*np.fft.irfft(r_hat,n=2*N)
    s = np.zeros(N)
    for i in range(N):
        s[i] = h[i]*r[i]
    s_hat = np.fft.rfft(s, n=2*N)
    return s_hat


